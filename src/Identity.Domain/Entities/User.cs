using Identity.Domain.Common;

namespace Identity.Domain.Entities;

public class User : BaseEntity
{
    public required string Email { get; set; }
    public string? PasswordHash { get; set; }

    public bool EmailVerified { get; set; }
    public string? EmailVerificationCodeHash { get; set; }
    public DateTime? EmailVerificationExpiresAt { get; set; }
    public DateTime? EmailVerificationSentAt { get; set; }
    public int EmailVerificationAttempts { get; set; }
    public DateTime? EmailVerificationWindowStartedAt { get; set; }
    public int EmailVerificationSendsInWindow { get; set; }

    public string? PasswordResetTokenHash { get; set; }
    public DateTime? PasswordResetExpiresAt { get; set; }
    public DateTime? PasswordResetSentAt { get; set; }

    /// <summary>Locked by an admin (indefinitely, until unlocked): cannot log in, refresh or reset the password.</summary>
    public DateTime? LockedAt { get; set; }

    public bool MfaEnabled { get; set; }

    /// <summary>TOTP secret, encrypted (AES-GCM, bound to the user id). Never stored in clear.</summary>
    public string? MfaSecretEncrypted { get; set; }

    /// <summary>Secret generated by setup, waiting for the first valid code to be enabled.</summary>
    public string? MfaPendingSecretEncrypted { get; set; }

    /// <summary>Last accepted TOTP time step: a code is accepted only once, even within its validity window.</summary>
    public long? MfaLastUsedTimeStep { get; set; }

    public ICollection<Session> Sessions { get; set; } = [];
    public ICollection<UserRole> UserRoles { get; set; } = [];
    public ICollection<MfaRecoveryCode> RecoveryCodes { get; set; } = [];
}
